import { test, expect, type Page } from "@playwright/test";
import { randomBytes } from "node:crypto";
const complete = "x + 3 = 7\nx = 7 - 3\nx = 4";
async function account(page: Page, role: "teacher" | "student", id: string, code?: string) {
  await page.goto(`/signup?role=${role}`);
  if (code) await page.getByLabel("Class join code").fill(code);
  await page.getByLabel("Your name").fill(role === "teacher" ? "Teacher" : "Student");
  await page.getByLabel("Username", { exact: true }).fill(`${role}_${id}`);
  await page.getByLabel("Passphrase", { exact: true }).fill("a safe classroom phrase");
  await page.getByRole("button", { name: role === "teacher" ? "Create account" : "Join class", exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
}
test("multiple problems collapse after approval; review corrections are audited and released independently", async ({ browser }) => {
  const teacherContext = await browser.newContext(), studentContext = await browser.newContext();
  const teacher = await teacherContext.newPage(), student = await studentContext.newPage();
  const id = randomBytes(4).toString("hex");
  try {
    await account(teacher, "teacher", id);
    await teacher.getByLabel("Class name").fill("Algebra");
    await teacher.getByRole("button", { name: "Create class", exact: true }).click();
    const studentsBox = teacher.getByRole("region", { name: "Students", exact: true });
    const assignmentsBox = teacher.getByRole("region", { name: "Assignments", exact: true });
    const publisher = teacher.getByRole("region", { name: "Publish assignment", exact: true });
    await expect(studentsBox).toBeVisible(); await expect(assignmentsBox).toBeVisible();
    expect((await assignmentsBox.boundingBox())!.y).toBeLessThan((await publisher.boundingBox())!.y);
    await teacher.getByLabel("Assignment title").fill("Two problem assignment");
    await teacher.getByRole("button", { name: "Approve rubric for problem 1", exact: true }).click();
    await expect(teacher.locator("details.problem-editor").nth(0)).not.toHaveAttribute("open");
    await teacher.getByRole("button", { name: "Add problem", exact: true }).click();
    const second = teacher.locator("details.problem-editor").nth(1);
    await second.getByLabel("Question", { exact: true }).fill("Solve x + 3 = 7. Show your work.");
    await second.getByLabel("Expected answers, one per line").fill("x = 4\n4");
    await second.getByLabel("Teacher solution", { exact: true }).fill(complete);
    await second.getByRole("button", { name: "Approve rubric for problem 2", exact: true }).click();
    await expect(second).not.toHaveAttribute("open");
    await teacher.getByRole("button", { name: "Publish assignment", exact: true }).click();
    await expect(assignmentsBox.getByRole("link", { name: "Two problem assignment", exact: true })).toBeVisible();
    await expect(publisher).toBeVisible();
    const code = await teacher.locator(".join-code-box code").innerText();
    await account(student, "student", id, code);
    await student.getByRole("link", { name: "Two problem assignment", exact: true }).click();
    const firstWork = student.getByRole("region", { name: "Problem 1", exact: true });
    const secondWork = student.getByRole("region", { name: "Problem 2", exact: true });
    await expect(firstWork.getByTestId("problem-status")).toHaveText("Not submitted");
    await expect(secondWork.getByTestId("problem-status")).toHaveText("Not submitted");
    await expect(student.getByTestId("assignment-status")).toContainText("0 / 2 problems submitted");
    await firstWork.getByLabel("Your work").fill(complete); await firstWork.getByRole("button", { name: "Submit answer", exact: true }).click();
    await expect(student.getByTestId("assignment-status")).toContainText("In progress");
    await expect(student.getByTestId("assignment-status")).toContainText("1 / 2 problems submitted");
    await secondWork.getByLabel("Your work").fill("x = 4"); await secondWork.getByRole("button", { name: "Submit answer", exact: true }).click();
    await expect(secondWork.getByTestId("problem-status")).toHaveText("Waiting for teacher");
    await expect(student.getByTestId("assignment-status")).toContainText("Waiting for teacher");
    await expect(student.getByTestId("assignment-status")).toContainText("2 / 2 problems submitted");
    await expect(student.getByTestId("draft-grade")).toHaveCount(0);
    await teacher.getByRole("region", { name: "Students", exact: true }).getByRole("link", { name: "Student", exact: true }).click();
    await expect(teacher.getByRole("region", { name: "Student detail", exact: true })).toBeVisible();
    await expect(teacher.getByRole("cell", { name: "14 / 20 draft", exact: true })).toBeVisible();
    await teacher.getByRole("link", { name: "Two problem assignment", exact: true }).click();
    await expect(teacher).toHaveURL(/\?assignment=/);
    await expect(teacher.getByRole("region", { name: "Assignment detail", exact: true })).toBeVisible();
    const assignmentURL = teacher.url();
    await teacher.getByRole("link", { name: "Review pending answers", exact: true }).click();
    await expect(teacher.getByRole("heading", { name: "Two problem assignment · Problem 2", exact: true })).toBeVisible();
    await teacher.getByRole("heading", { name: "Review answers", exact: true }).click();
    await teacher.keyboard.press("ArrowRight");
    await expect(teacher.getByRole("heading", { name: "Two problem assignment · Problem 1", exact: true })).toBeVisible();
    await teacher.keyboard.press("ArrowLeft");
    await expect(teacher.getByRole("heading", { name: "Two problem assignment · Problem 2", exact: true })).toBeVisible();
    await teacher.getByRole("button", { name: "Line 0", exact: true }).first().click();
    await expect(teacher.locator(".evidence-highlight").first()).toBeVisible();
    await teacher.getByLabel("Score: Show the subtraction step", { exact: true }).fill("3");
    await teacher.getByLabel("Student feedback", { exact: true }).fill("Show the subtraction step next time.");
    await teacher.getByLabel("Reason for correction", { exact: true }).fill("Partial reasoning credit after inspection.");
    await expect(teacher.getByRole("button", { name: "Next", exact: true })).toBeDisabled();
    await teacher.getByRole("button", { name: "Save correction", exact: true }).click();
    await expect(teacher.getByText("Override history (1)", { exact: true })).toBeVisible();
    const settings = await teacherContext.newPage(); await settings.goto(assignmentURL);
    const visibility = settings.getByLabel("Show draft grades to students while awaiting teacher approval");
    await visibility.check();
    await expect(secondWork.getByTestId("draft-grade")).toContainText("7 points");
    await expect(student.getByTestId("assignment-draft-total")).toContainText("17 / 20");
    await expect(secondWork.getByTestId("draft-grade")).toContainText("Show the subtraction step next time.");
    await visibility.uncheck(); await expect(student.getByTestId("draft-grade")).toHaveCount(0);
    await expect(student.getByTestId("assignment-draft-total")).toHaveCount(0);
    await settings.close();
    await teacher.getByRole("button", { name: "Approve and release", exact: true }).click();
    await expect(secondWork.getByTestId("final-grade")).toContainText("7 points");
    await expect(student.getByTestId("assignment-final-total")).toHaveCount(0);
    await expect(student.getByTestId("assignment-partial-total")).toContainText("Approved points so far: 7 / 20");
    await expect(teacher.getByRole("heading", { name: "Two problem assignment · Problem 1", exact: true })).toBeVisible();
    await teacher.getByRole("button", { name: "Approve and release", exact: true }).click();
    await expect(student.getByTestId("assignment-final-total")).toContainText("17 / 20 final");
    await expect(student.getByTestId("final-grade")).toHaveCount(2);
    await teacher.getByLabel("Review filter", { exact: true }).selectOption("all");
    await teacher.getByText("Override history (1)", { exact: true }).click();
    await expect(teacher.getByText("Partial reasoning credit after inspection.", { exact: false })).toBeVisible();
    const ownData = await (await student.request.get("/api/practice")).json();
    expect(ownData.submissions.every((item: { originalGrade: unknown; overrideHistory: unknown[] }) => item.originalGrade === null && item.overrideHistory.length === 0)).toBe(true);
    if (process.env.UPDATE_SCREENSHOTS === "1") {
      await teacher.screenshot({ path: "docs/screenshots/review-deck.png", fullPage: true });
      await student.screenshot({ path: "docs/screenshots/multiple-problems.png", fullPage: true });
    }
  } finally { await teacherContext.close(); await studentContext.close(); }
});
